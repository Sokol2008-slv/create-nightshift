// ПРОБЛЕМА (leak_audit.json general_notes.trades): фермер продаёт урожай за
// изумруды уже в P0 (без единого куска металла), а изумруды дальше тратятся у
// священника/каменщика/бродячего торговца на редстоун/лазурит/кварц/уголь —
// то есть P3-ресурсы покупаются за P0-валюту в обход добычи руды. Village-
// трейды в 1.21 жёстко зашиты в ванильном Java-коде (VillagerTrades.java) — НЕ
// датапак, поэтому AStages Item/Loot Restriction их не видят вообще.
//
// РЕШЕНИЕ: вместо попытки вычистить конкретные офферы (нужен полноценный
// datapack override VillagerTrades или мод-хук), просто закрываем САМ ЭКРАН
// торговли через AStages Screen Restriction на MenuType "minecraft:merchant" —
// это единый GUI и для жителей-специалистов, и для бродячего торговца (Wandering
// Trader), так что одна рестрикция закрывает оба канала утечки разом.
//
// ПРОВЕРЕНО ПО КОДУ: AScreenRestriction принимает MenuType<?> (см. javap
// KubeJSServerUtils.addRestrictionForScreen), а "minecraft:merchant" — это id
// ванильного MenuType.MERCHANT в реестре меню (стандартный registry name,
// НЕ верифицировано напрямую в этой jar-сборке, но это стабильный ванильный id
// с версии 1.14, менялся крайне маловероятно). ПРОВЕРИТЬ на тестовом сервере:
// откройте торговлю жителя ДО выдачи nightshift:p3 — GUI должен не открываться
// и показывать openMessage().
//
// ПОБОЧНЫЙ ЭФФЕКТ (важно): это заблокирует ЛЮБУЮ торговлю через меню
// "minecraft:merchant", включая потенциальных кастомных торговцев из других
// модов пака, если они переиспользуют тот же ванильный MenuType (многие моды
// так и делают, чтобы не городить свой GUI). Если в паке есть, например,
// NPC-торговец квестовой линии или маркет-мод, использующий тот же MenuType —
// его тоже закроет эта рестрикция. НЕ проверялось на предмет таких конфликтов —
// см. README, риск №4.

if (!NS_OPEN_WORLD) {
AStages.addRestrictionForScreen('nightshift:screen/villager_trade', 'nightshift_p3', 'minecraft:merchant')
    .openMessage(function (menuType) {
        return Component.literal('Торговля закрыта: мир ещё не готов доверять чужакам (нужна фаза 3).').red()
    })

// Если побочный эффект выше окажется проблемой (закрывает что-то лишнее),
// альтернативный, более узкий (но более хрупкий) путь — setChecker(), который
// умеет отличать чанки/блоки/entity через blockState/blockEntity/menu (см.
// wiki/AStages-Screen-Restriction.md, "Custom Checker"). Для мерчанта
// blockState/blockEntity будут null (это не блок, а сущность-житель), так что
// придётся различать по самому menu (abstractContainerMenu instanceof
// MerchantMenu, дальше смотреть menu.getTrader() -> is Villager/WanderingTrader
// vs что-то ещё) — не реализовано в этом черновике, т.к. требует более глубокого
// знания Java-классов конкретных модов-конкурентов за тот же MenuType.
}

// ==========================================================================
// Imposter (двойники игроков с ножом) убран из игры (Георгий, 28.09: «копии наши очень часто появляются
// и бьют ножом»). Пока мод стоит в сборке, его существа не появляются никак: спавн отменяется.
// Сам мод уходит из пака при ближайшем перезаходе (packwiz remove).
// ==========================================================================
var NS_NO_IMPOSTER = ['imposter:imposter', 'imposter:cutout']

for (var nsImpI = 0; nsImpI < NS_NO_IMPOSTER.length; nsImpI++) {
	EntityEvents.spawned(NS_NO_IMPOSTER[nsImpI], event => {
		event.cancel()
	})
}

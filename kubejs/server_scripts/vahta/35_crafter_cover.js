// Крышка слота крафтера — рано и дёшево (Георгий, 29.09: алмазная палочка «не крафтится — тут диагональ»).
// Механические крафтеры собираются в группу только стенка к стенке; у диагональных и «дырявых» рецептов
// (палочки, ножницы, удочка…) нужные клетки касаются углами. Пустые клетки заполняют крафтеры с крышкой
// слота (ПКМ крышкой по крафтеру) — они держат группу и считаются пустыми. Штатная крышка — из 3 латунных
// самородков (латунь только с горелкой), поэтому на вахте ещё и прессом из железной решётки: у неё других
// рецептов пресса нет (самородки железа и меди пресс штампует в монеты Create Deco; ванильного медного
// самородка в 1.21.1 ещё нет).
// ==========================================================================
ServerEvents.recipes(event => {
	event.recipes.create.pressing('create:crafter_slot_cover', 'minecraft:iron_bars').id('nightshift:vahta/pressing/crafter_slot_cover')
})

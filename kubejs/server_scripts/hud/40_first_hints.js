// первые 10 с после входа инвентарь «меняется» целиком (синхронизация) — подсказки не сыплем стеной при входе
var NS_FH_JOIN = {}
PlayerEvents.loggedIn(event => {
	try {
		NS_FH_JOIN[String(event.getPlayer().getUsername())] = Number(event.server.getTickCount())
	} catch (e) {}
})

PlayerEvents.inventoryChanged(event => {
	try {
		var joined = NS_FH_JOIN[String(event.getPlayer().getUsername())]
		if (joined !== undefined && Number(event.getPlayer().getServer().getTickCount()) - joined < 200) return
		var it = event.getItem()
		if (!it || it.isEmpty()) return
		var h = NS_FH[String(it.getId())]
		if (!h) return
		var p = event.getPlayer()
		var tag = 'ns_fh_' + h[0]
		if (p.getTags().contains(tag)) return
		p.addTag(tag)
		p.tell(Text.gold('[Подсказка] ').append(Text.white(h[1])).append(Text.darkGray(' Подробно — JEI (U).')))
	} catch (e) {
		console.warn('[first_hints] ' + e)
	}
})

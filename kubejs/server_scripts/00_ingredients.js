// ==========================================================================
// Ночная смена — теги предметов в рецептах Create.
// KubeJS Create 2101: ингредиент рецепта Create — «жидкость или предмет», и строка '#тег'
// читается как тег ЖИДКОСТИ (пустой) — рецепт либо отклоняется («more fluid inputs than
// supported»), либо молча ломается. Поэтому теги предметов оборачиваем в Ingredient.of.
// Проверено на витрине 28.09: 862 рецепта «Вахты» падали именно из-за этого.
// ==========================================================================

// '#тег' → Ingredient.of('#тег'); остальное без изменений
function nsIng(x) {
	if (typeof x === 'string' && x.charAt(0) === '#') return Ingredient.of(x)
	return x
}

// то же для списка ингредиентов
function nsIngs(list) {
	var res = []
	for (var i = 0; i < list.length; i++) res.push(nsIng(list[i]))
	return res
}

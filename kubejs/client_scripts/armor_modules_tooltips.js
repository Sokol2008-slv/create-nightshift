var NS_AM_TIPS = {
	'nightshift:module_spring_boots': ['Ботинки: урона от падения нет совсем.', 'Прыгай с любой высоты — земля сама извинится.'],
	'nightshift:module_step_assist': ['Ботинки: шаг на целый блок без прыжка (высота шага 0,6 → 1,1).'],
	'nightshift:module_sprint': ['Поножи: скорость +30 % (зелье скорости I — +20 %).'],
	'nightshift:module_jump_springs': ['Поножи: прыжок ~2,2 блока вместо 1,25 — стена в два блока больше не стена.'],
	'nightshift:module_armor_plate': ['Нагрудник: защита +4, вязкость +2, отбрасывает на 10 % слабее.', 'Потолок защиты в игре — 30.'],
	'nightshift:module_night_vision': ['Шлем: ночное зрение, пока шлем надет. Сняли — эффект гаснет.']
}
var NS_AM_HOW = 'Ставится механическими крафтерами: модуль + вещь рядом (раскладка любая). Чары и прочность сохраняются; второй такой же модуль на вещь не встанет.'

ItemEvents.modifyTooltips(function (event) {
	for (var id in NS_AM_TIPS) {
		var lines = [Text.gold('Модуль брони')]
		for (var i = 0; i < NS_AM_TIPS[id].length; i++) lines.push(Text.gray(NS_AM_TIPS[id][i]))
		lines.push(Text.darkGray(NS_AM_HOW))
		event.add(id, lines)
	}
	event.add('nightshift:incomplete_armor_module', [Text.gray('Заготовка модуля: собирается по шагам — деплоер, деплоер, пресс.')])
})


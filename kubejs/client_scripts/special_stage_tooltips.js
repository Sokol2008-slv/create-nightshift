// Подсказки к ключам особых стадий (raids/45_special_stages.js, startup_scripts/vahta/26_special_stage_items.js)
ItemEvents.modifyTooltips(event => {
	var keys = [
		['coil_core', 'Механоиды (22, 44, 64): орду берёт только ток тесла-башни.'],
		['afterburner_blueprint', 'Воздушный бой (24, 42, 58): ульи-матки в небе, бить только с самолёта.'],
		['otk_armor_plate', 'Бронеколонна (26, 48, 68): броню пробивают только турели, пушки и взрывы.'],
		['runner_badge', 'Побег (28, 46, 62): добежать до точки эвакуации, пока Пожиратель не догнал.'],
		['spirit_essence', 'Духи (32, 52): орду ранит только магия.'],
		['queen_heart', 'Штурм гнезда (36, 54, 66): найти гнездо и убить матку до рассвета.'],
		['prism_lens', 'Невидимки (34) и Блэкаут (56): орду видно только в луче прожектора.']
	]
	for (var i = 0; i < keys.length; i++) {
		event.add('nightshift:' + keys[i][0], [
			Text.gold('Ключ особой стадии.'),
			Text.gray(keys[i][1]),
			Text.gray('Выдаётся за первое прохождение стадии. Не продаётся на столе трансмутации.')
		])
	}
})

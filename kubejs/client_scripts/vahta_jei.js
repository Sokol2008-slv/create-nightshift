// ==========================================================================
// «Вахта» — JEI не путает станциями ручного крафта (Георгий, 28.09: «верстак пишется, но
// скрафтить не выйдет»).
//  - Прячем то, чего на вахте нет совсем: философский камень, крафт-апгрейды рюкзаков и хранилищ,
//    ванильный автокрафтер, чертёж Create. Скрытый предмет JEI не показывает и как станцию рецепта.
//  - Верстак НЕ прячем: если скрыть все станции категории «Создание», JEI прячет её целиком, и
//    пропадают рецепты из одного предмета (их делает одиночный механический крафтер, у Create своей
//    вкладки для них нет). Верстак в языке — «Мёртвый верстак» (kubejs/assets/minecraft/lang),
//    в JEI на нём пояснение. Добавить механический крафтер станцией к «Созданию» KubeJS не умеет.
// ==========================================================================
var NS_VAHTA_JEI_HIDE = [
	'minecraft:crafter', // ванильный автокрафтер — рецепт убран, окно отменено
	'projecte:philosophers_stone', // убран (server_scripts/vahta/30_projecte.js)
	'sophisticatedbackpacks:crafting_upgrade', // карманные верстаки и камнерезы — убраны (vahta/20_recipes.js)
	'sophisticatedstorage:crafting_upgrade',
	'sophisticatedbackpacks:stonecutter_upgrade',
	'sophisticatedstorage:stonecutter_upgrade',
	'create:crafting_blueprint'
]

RecipeViewerEvents.removeEntries('item', event => {
	for (var i = 0; i < NS_VAHTA_JEI_HIDE.length; i++) event.remove(NS_VAHTA_JEI_HIDE[i])
})

RecipeViewerEvents.addInformation('item', event => {
	event.add('minecraft:crafting_table', [
		'На вахте верстак мёртв: окно не открывается, сетка 2×2 в инвентаре тоже не работает.',
		'Рецепты вкладки «Создание» делают машины Create:',
		'• фигурные — механические крафтеры по раскладке (вкладка «Форменное создание»);',
		'• бесформенные — миксер над бассейном, из одного предмета — один механический крафтер;',
		'• квадрат 2×2 или 3×3 из одного предмета — пресс над бассейном.'
	])
})
